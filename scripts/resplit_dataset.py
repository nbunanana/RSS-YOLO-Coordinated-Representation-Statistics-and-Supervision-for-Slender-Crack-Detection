"""Re-split the Crack-Seg dataset to 7:1:2 (rounded by ratio) with a fixed split seed.

- The original split is left untouched, which allows rollback and comparison;
- a new datasets/crack-seg-712/ directory receives a copy of every image and label after re-assignment;
- datasets/crack-seg-712.yaml and split_manifest.csv are also written; the manifest records the split of every image, so the result is reproducible.

Usage:
    python resplit_dataset.py
    python resplit_dataset.py --ratios 0.7 0.1 0.2
"""
import argparse
import csv
import os
import random
import shutil
from pathlib import Path

DS = Path(os.environ.get("CRACK_DATA_ROOT", "D:/yolov8/ultralytics-main/datasets"))
SRC = DS / "crack-seg"
DST = DS / "crack-seg-712"
IMG_EXT = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def collect():
    items = []
    for split in ("train", "val", "test"):
        idir = SRC / "images" / split
        if not idir.exists():
            raise SystemExit(f"missing directory: {idir}")
        for img in sorted(idir.iterdir()):
            if img.suffix.lower() not in IMG_EXT:
                continue
            items.append((img, SRC / "labels" / split / f"{img.stem}.txt", split))
    return items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--ratios", nargs=3, type=float, default=[0.7, 0.1, 0.2])
    args = ap.parse_args()

    if DST.exists():
        raise SystemExit(f"{DST} already exists; delete or rename it first so that old and new data are not mixed")

    items = collect()
    n = len(items)

    # validation: every label is present and the stems are unique
    missing = [str(i[0]) for i in items if not i[1].exists()]
    if missing:
        raise SystemExit(f"{len(missing)} images have no label, for example: {missing[0]}")
    stems = [i[0].stem for i in items]
    if len(set(stems)) != n:
        raise SystemExit("duplicate image file names (stems) would break the image-label pairing")

    n_tr = round(n * args.ratios[0])
    n_va = round(n * args.ratios[1])
    n_te = n - n_tr - n_va

    random.Random(args.seed).shuffle(items)
    assign = (
        [("train", it) for it in items[:n_tr]]
        + [("val", it) for it in items[n_tr : n_tr + n_va]]
        + [("test", it) for it in items[n_tr + n_va :]]
    )

    for split in ("train", "val", "test"):
        (DST / "images" / split).mkdir(parents=True, exist_ok=True)
        (DST / "labels" / split).mkdir(parents=True, exist_ok=True)

    for split, (img, lab, _orig) in assign:
        shutil.copy2(img, DST / "images" / split / img.name)
        shutil.copy2(lab, DST / "labels" / split / lab.name)

    (DS / "crack-seg-712.yaml").write_text(
        "# Crack-Seg re-split (7:1:2), generated by scripts/resplit_dataset.py\n"
        f"# split seed={args.seed}, ratios={args.ratios}\n"
        "path: crack-seg-712\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n\n"
        "names:\n  0: crack\n",
        encoding="utf-8",
    )

    with open(DST / "split_manifest.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["stem", "split"])
        for split, (img, _lab, _orig) in assign:
            w.writerow([img.stem, split])

    print("=" * 60)
    orig_counts = {s: sum(1 for it in items if it[2] == s) for s in ("train", "val", "test")}
    print(f"original split : train={orig_counts['train']}  val={orig_counts['val']}  test={orig_counts['test']}")
    print(f"total          : {n}")
    print(f"new split      : train={n_tr}  val={n_va}  test={n_te}   (split seed={args.seed})")
    for split in ("train", "val", "test"):
        c = len(list((DST / "images" / split).iterdir()))
        cl = len(list((DST / "labels" / split).iterdir()))
        print(f"  images/{split} = {c}   labels/{split} = {cl}")
    print(f"dataset directory: {DST}")
    print(f"yaml             : {DS / 'crack-seg-712.yaml'}")
    print(f"manifest         : {DST / 'split_manifest.csv'}")
    print("=" * 60)


if __name__ == "__main__":
    main()
